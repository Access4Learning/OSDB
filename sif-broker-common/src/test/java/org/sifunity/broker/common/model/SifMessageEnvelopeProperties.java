package org.sifunity.broker.common.model;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import net.jqwik.api.*;
import org.sifunity.broker.common.constant.MessageType;
import org.sifunity.broker.common.constant.ServiceType;

import java.time.Instant;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Property-based tests for SifMessageEnvelope.
 * Tests universal properties like auto-generation of messageId and timestamp.
 */
class SifMessageEnvelopeProperties {

    private static final ObjectMapper objectMapper = createObjectMapper();

    private static ObjectMapper createObjectMapper() {
        ObjectMapper mapper = new ObjectMapper();
        mapper.registerModule(new JavaTimeModule());
        mapper.disable(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS);
        return mapper;
    }

    // ========== Arbitraries (Generators) ==========

    @Provide
    Arbitrary<MessageType> messageTypes() {
        return Arbitraries.of(MessageType.values());
    }

    @Provide
    Arbitrary<ServiceType> serviceTypes() {
        return Arbitraries.of(ServiceType.values());
    }

    @Provide
    Arbitrary<String> serviceNames() {
        return Arbitraries.strings()
            .alpha()
            .ofMinLength(1)
            .ofMaxLength(50);
    }

    @Provide
    Arbitrary<String> zoneIds() {
        return Arbitraries.strings()
            .alpha()
            .numeric()
            .ofMinLength(1)
            .ofMaxLength(30);
    }

    @Provide
    Arbitrary<String> contextIds() {
        return Arbitraries.strings()
            .alpha()
            .numeric()
            .ofMinLength(1)
            .ofMaxLength(30);
    }

    @Provide
    Arbitrary<UUID> uuids() {
        return Arbitraries.create(UUID::randomUUID);
    }

    @Provide
    Arbitrary<String> payloads() {
        return Arbitraries.strings()
            .ofMinLength(0)
            .ofMaxLength(100);
    }

    @Provide
    Arbitrary<SifMessageEnvelope<String>> envelopesWithoutIds() {
        return Combinators.combine(
            messageTypes(),
            serviceNames(),
            serviceTypes(),
            zoneIds().injectNull(0.3),
            contextIds().injectNull(0.3),
            payloads().injectNull(0.2)
        ).as((messageType, serviceName, serviceType, zoneId, contextId, payload) ->
            SifMessageEnvelope.<String>builder()
                .messageType(messageType)
                .serviceName(serviceName)
                .serviceType(serviceType)
                .zoneId(zoneId)
                .contextId(contextId)
                .payload(payload)
                .build()
        );
    }

    @Provide
    Arbitrary<SifMessageEnvelope<String>> envelopesWithIds() {
        return Combinators.combine(
            uuids(),
            Arbitraries.longs().between(0, System.currentTimeMillis()).map(Instant::ofEpochMilli),
            messageTypes(),
            serviceNames(),
            serviceTypes(),
            zoneIds().injectNull(0.3),
            contextIds().injectNull(0.3),
            uuids().injectNull(0.3).map(u -> u != null ? u.toString() : null)
        ).flatAs((messageId, timestamp, messageType, serviceName, serviceType, zoneId, contextId, requestId) ->
            Combinators.combine(
                uuids().injectNull(0.3),
                uuids().injectNull(0.3),
                payloads().injectNull(0.2)
            ).as((queueId, sourceId, payload) ->
                SifMessageEnvelope.<String>builder()
                    .messageId(messageId)
                    .timestamp(timestamp)
                    .messageType(messageType)
                    .serviceName(serviceName)
                    .serviceType(serviceType)
                    .zoneId(zoneId)
                    .contextId(contextId)
                    .requestId(requestId)
                    .queueId(queueId)
                    .sourceId(sourceId)
                    .payload(payload)
                    .build()
            )
        );
    }

    // ========== Property 4: SIF Envelope Auto-Generation ==========
    // **Validates: Requirements 2.5, 2.6**

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void messageIdIsAutoGenerated_whenNotProvided(@ForAll("envelopesWithoutIds") SifMessageEnvelope<String> envelope) {
        // When messageId is not explicitly provided, it should be auto-generated
        assertThat(envelope.getMessageId()).isNotNull();
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void timestampIsAutoGenerated_whenNotProvided(@ForAll("envelopesWithoutIds") SifMessageEnvelope<String> envelope) {
        // When timestamp is not explicitly provided, it should be auto-generated
        assertThat(envelope.getTimestamp()).isNotNull();
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void autoGeneratedMessageIdIsValidUUID(@ForAll("envelopesWithoutIds") SifMessageEnvelope<String> envelope) {
        // Auto-generated messageId should be a valid UUID
        UUID messageId = envelope.getMessageId();
        assertThat(messageId).isNotNull();
        assertThat(messageId.toString()).matches("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$");
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void autoGeneratedTimestampIsReasonable(@ForAll("envelopesWithoutIds") SifMessageEnvelope<String> envelope) {
        // Auto-generated timestamp should be close to current time (within 1 second)
        Instant now = Instant.now();
        Instant timestamp = envelope.getTimestamp();
        
        assertThat(timestamp).isNotNull();
        assertThat(timestamp).isBetween(now.minusSeconds(1), now.plusSeconds(1));
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void explicitMessageIdIsPreserved(@ForAll("envelopesWithIds") SifMessageEnvelope<String> envelope,
                                      @ForAll("uuids") UUID expectedMessageId) {
        // When messageId is explicitly provided, it should be preserved
        SifMessageEnvelope<String> envelopeWithId = SifMessageEnvelope.<String>builder()
            .messageId(expectedMessageId)
            .messageType(envelope.getMessageType())
            .serviceName(envelope.getServiceName())
            .serviceType(envelope.getServiceType())
            .build();
        
        assertThat(envelopeWithId.getMessageId()).isEqualTo(expectedMessageId);
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void explicitTimestampIsPreserved(@ForAll("envelopesWithIds") SifMessageEnvelope<String> envelope) {
        // When timestamp is explicitly provided, it should be preserved
        Instant expectedTimestamp = Instant.parse("2024-01-01T00:00:00Z");
        
        SifMessageEnvelope<String> envelopeWithTimestamp = SifMessageEnvelope.<String>builder()
            .timestamp(expectedTimestamp)
            .messageType(envelope.getMessageType())
            .serviceName(envelope.getServiceName())
            .serviceType(envelope.getServiceType())
            .build();
        
        assertThat(envelopeWithTimestamp.getTimestamp()).isEqualTo(expectedTimestamp);
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void autoGeneratedMessageIdsAreUnique(@ForAll("messageTypes") MessageType messageType,
                                          @ForAll("serviceNames") String serviceName,
                                          @ForAll("serviceTypes") ServiceType serviceType) {
        // Multiple envelopes created without explicit messageId should have unique IDs
        SifMessageEnvelope<String> envelope1 = SifMessageEnvelope.<String>builder()
            .messageType(messageType)
            .serviceName(serviceName)
            .serviceType(serviceType)
            .build();

        SifMessageEnvelope<String> envelope2 = SifMessageEnvelope.<String>builder()
            .messageType(messageType)
            .serviceName(serviceName)
            .serviceType(serviceType)
            .build();

        assertThat(envelope1.getMessageId()).isNotEqualTo(envelope2.getMessageId());
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void autoGenerationWorksWithAllMessageTypes(@ForAll("messageTypes") MessageType messageType,
                                                @ForAll("serviceNames") String serviceName,
                                                @ForAll("serviceTypes") ServiceType serviceType) {
        // Auto-generation should work regardless of message type
        SifMessageEnvelope<String> envelope = SifMessageEnvelope.<String>builder()
            .messageType(messageType)
            .serviceName(serviceName)
            .serviceType(serviceType)
            .build();

        assertThat(envelope.getMessageId()).isNotNull();
        assertThat(envelope.getTimestamp()).isNotNull();
        assertThat(envelope.getMessageType()).isEqualTo(messageType);
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void autoGenerationWorksWithOptionalFields(@ForAll("messageTypes") MessageType messageType,
                                               @ForAll("serviceNames") String serviceName,
                                               @ForAll("serviceTypes") ServiceType serviceType,
                                               @ForAll("zoneIds") String zoneId,
                                               @ForAll("contextIds") String contextId) {
        // Auto-generation should work even when optional fields are provided
        SifMessageEnvelope<String> envelope = SifMessageEnvelope.<String>builder()
            .messageType(messageType)
            .serviceName(serviceName)
            .serviceType(serviceType)
            .zoneId(zoneId)
            .contextId(contextId)
            .build();

        assertThat(envelope.getMessageId()).isNotNull();
        assertThat(envelope.getTimestamp()).isNotNull();
        assertThat(envelope.getZoneId()).isEqualTo(zoneId);
        assertThat(envelope.getContextId()).isEqualTo(contextId);
    }

    @Property
    @Tag("Feature-sif-broker-common-Property-4-SIF-Envelope-Auto-Generation")
    void jsonSerializationPreservesAutoGeneratedFields(@ForAll("envelopesWithoutIds") SifMessageEnvelope<String> original) throws Exception {
        // Auto-generated fields should survive JSON serialization round-trip
        String json = objectMapper.writeValueAsString(original);
        SifMessageEnvelope<?> deserialized = objectMapper.readValue(json, SifMessageEnvelope.class);

        assertThat(deserialized.getMessageId()).isEqualTo(original.getMessageId());
        assertThat(deserialized.getTimestamp()).isEqualTo(original.getTimestamp());
    }
}
