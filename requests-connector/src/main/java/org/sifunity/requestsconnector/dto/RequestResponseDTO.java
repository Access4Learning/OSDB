package org.sifunity.requestsconnector.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import java.time.Instant;
import java.util.Collections;
import java.util.Map;
import java.util.UUID;

/**
 * DTO for request responses in both IMMEDIATE and DELAYED patterns.
 * 
 * This DTO represents the response returned to consumers after processing their requests.
 * 
 * For IMMEDIATE requests:
 * - messageId: The unique identifier for the request/response
 * - timestamp: When the response was generated
 * - payload: The actual response data from the provider
 * - queueId and status are null
 * 
 * For DELAYED requests:
 * - messageId: The unique identifier for tracking the asynchronous request
 * - queueId: The consumer's queue where the response will be delivered
 * - status: "ACCEPTED" indicating the request has been accepted for processing
 * - timestamp: When the request was accepted
 * - payload is null (actual response delivered to queue later)
 * 
 * Validates Requirements 1.3, 4.5, 5.3
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class RequestResponseDTO {
    
    /**
     * Unique identifier for the request/response message.
     * Generated by the Requests Connector for tracking and correlation.
     */
    private UUID messageId;
    
    /**
     * The consumer's queue identifier for receiving DELAYED responses.
     * Only populated for DELAYED requests, null for IMMEDIATE requests.
     */
    private UUID queueId;
    
    /**
     * Status of the request processing.
     * For DELAYED requests: "ACCEPTED" indicating the request has been accepted for asynchronous processing.
     * For IMMEDIATE requests: null (response is synchronous).
     */
    private String status;
    
    /**
     * The requestId correlation token for this request.
     * For DELAYED requests: echoes the consumer-supplied requestId (or the generated messageId
     * if none was supplied). This is the token that will tag all response pages.
     * For IMMEDIATE requests: null.
     */
    private String requestId;
    
    /**
     * Timestamp when the response was generated (IMMEDIATE) or when the request was accepted (DELAYED).
     */
    private Instant timestamp;
    
    /**
     * The response payload containing the actual data.
     * For IMMEDIATE requests: Contains the provider's response data.
     * For DELAYED requests: null (actual response delivered to consumer's queue later).
     */
    private Object payload;
    
    /**
     * Sanitized passthrough headers from the provider's response.
     * For IMMEDIATE requests: Contains non-blacklisted headers from the provider's HTTP response.
     * For DELAYED requests: null (headers are carried in the SifMessageEnvelope delivered via queue).
     * Defaults to an empty map when not set.
     */
    @Builder.Default
    private Map<String, String> headers = Collections.emptyMap();
}
