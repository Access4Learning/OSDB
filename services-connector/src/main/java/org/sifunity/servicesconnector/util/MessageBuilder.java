package org.sifunity.servicesconnector.util;

import org.sifunity.broker.common.constant.MessageType;
import org.sifunity.broker.common.constant.ServiceType;
import org.sifunity.broker.common.model.SifMessageEnvelope;
import org.springframework.stereotype.Component;

import java.util.Collections;
import java.util.Map;
import java.util.UUID;

/**
 * Utility class for building SIF message envelopes for functional service requests.
 *
 * <p>Constructs properly formatted {@link SifMessageEnvelope} instances with
 * {@code serviceType=FUNCTIONAL} for both IMMEDIATE and DELAYED request patterns.
 * The messageId and timestamp are automatically generated by the envelope's
 * builder defaults.</p>
 *
 * <p>Mirrors the requests-connector's {@code MessageBuilder} but is tailored
 * for functional services: the service name comes from the URL path variable,
 * the payload is a raw {@code Object}, and the service type is always
 * {@link ServiceType#FUNCTIONAL}.</p>
 *
 * <p><strong>Requirements:</strong> 5.1, 5.8</p>
 *
 * @see SifMessageEnvelope
 */
@Component
public class MessageBuilder {

    /**
     * Builds a SIF message envelope for an IMMEDIATE functional service request.
     *
     * <p>Creates an envelope with {@code serviceType=FUNCTIONAL},
     * {@code messageType=REQUEST}, the raw payload, and sanitized passthrough
     * headers. The messageId and timestamp are auto-generated.</p>
     *
     * @param functionalServiceName the functional service name from the URL path
     * @param environmentId         the consumer's environment ID
     * @param zoneId                the zone ID from SIF header
     * @param contextId             the context ID from SIF header (may be null)
     * @param requestBody           the raw request body (may be null for GET/DELETE)
     * @param passthroughHeaders    sanitized headers to forward to the provider
     * @return a SIF message envelope ready to be sent to the provider
     */
    public SifMessageEnvelope<Object> buildRequestEnvelope(
            String functionalServiceName,
            UUID environmentId,
            String zoneId,
            String contextId,
            Object requestBody,
            Map<String, String> passthroughHeaders) {

        return SifMessageEnvelope.<Object>builder()
                .messageType(MessageType.REQUEST)
                .serviceName(functionalServiceName)
                .serviceType(ServiceType.FUNCTIONAL)
                .zoneId(zoneId)
                .contextId(contextId)
                .sourceId(environmentId)
                .headers(passthroughHeaders != null ? passthroughHeaders : Collections.emptyMap())
                .payload(requestBody)
                .build();
    }

    /**
     * Builds a SIF message envelope for a DELAYED functional service request.
     *
     * <p>Creates an envelope identical to the IMMEDIATE envelope but with the
     * consumer's {@code queueId} set for response delivery routing.</p>
     *
     * @param functionalServiceName the functional service name from the URL path
     * @param environmentId         the consumer's environment ID
     * @param zoneId                the zone ID from SIF header
     * @param contextId             the context ID from SIF header (may be null)
     * @param queueId               the consumer's queue ID for response delivery
     * @param requestBody           the raw request body (may be null for GET/DELETE)
     * @param passthroughHeaders    sanitized headers to forward to the provider
     * @return a SIF message envelope ready to be queued for the provider
     */
    public SifMessageEnvelope<Object> buildDelayedRequestEnvelope(
            String functionalServiceName,
            UUID environmentId,
            String zoneId,
            String contextId,
            UUID queueId,
            String requestId,
            Object requestBody,
            Map<String, String> passthroughHeaders) {

        return SifMessageEnvelope.<Object>builder()
                .messageType(MessageType.REQUEST)
                .serviceName(functionalServiceName)
                .serviceType(ServiceType.FUNCTIONAL)
                .zoneId(zoneId)
                .contextId(contextId)
                .sourceId(environmentId)
                .queueId(queueId)
                .requestId(requestId)
                .headers(passthroughHeaders != null ? passthroughHeaders : Collections.emptyMap())
                .payload(requestBody)
                .build();
    }
}
