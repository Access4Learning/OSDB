package org.sifunity.responsesconnector.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.Instant;
import java.util.UUID;

/**
 * Data Transfer Object for API response results.
 * <p>
 * This DTO represents the result of a response routing operation. It is returned
 * to the provider or Requests Connector after successfully routing a response to
 * a consumer queue.
 * </p>
 * <p>
 * The DTO includes the generated message ID, the target queue ID, the routing status,
 * and a timestamp for tracking purposes.
 * </p>
 * 
 * <p>Example usage:
 * <pre>{@code
 * ResponseResultDTO result = ResponseResultDTO.builder()
 *     .messageId(UUID.randomUUID())
 *     .queueId(consumerQueueId)
 *     .status("DELIVERED")
 *     .timestamp(Instant.now())
 *     .build();
 * }</pre>
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ResponseResultDTO {
    
    /**
     * The unique identifier for the enqueued message.
     * This is generated by the Responses Connector when creating the message envelope.
     */
    private UUID messageId;
    
    /**
     * The identifier of the consumer queue where the response was delivered.
     * This is the queueId provided in the request headers.
     */
    private UUID queueId;
    
    /**
     * The status of the routing operation.
     * Possible values: "DELIVERED", "ERROR_DELIVERED"
     */
    private String status;
    
    /**
     * The timestamp when the response was routed.
     * This is set to the current time when the routing operation completes.
     */
    private Instant timestamp;
}
